#!/usr/bin/env python3
"""Tesserafin media validation bench (#342, chantier 2).

One scenario set, run against ONE server image on ONE machine, that records what
the FFmpeg runtime can do AND what Tesserafin actually serves:

  level "ffmpeg"    the image's own ffmpeg ran a command and the output probes
                    as expected. Proves the runtime + drivers, NOT playback.
  level "playback"  a real Tesserafin server, started from the image, served
                    HLS bytes over its HTTP API for a real library item, the
                    bytes probe as expected, and the server's own log names the
                    encoder/filters it used. This is the only level that counts
                    as "lecture réellement réussie".

Provider independence: every action goes through the `docker` CLI and nothing
else — no host bind mounts, no published ports, no host ffmpeg. Fixtures are
generated by the image itself into named volumes, HTTP is spoken from inside
the server container, files come back with `docker exec cat`. So the same
command runs locally or on any machine reachable as a Docker endpoint:

    DOCKER_HOST=ssh://user@gpu-host ci/media-bench/bench.py --image IMG ...

The cloud adapter therefore only has to provision a host with Docker and a GPU
and export DOCKER_HOST (see ci/media-bench/README.md).

Usage:
  ci/media-bench/bench.py --image IMAGE [--device /dev/dri/renderD128 | --no-device]
                          [--out DIR] [--only a,b,...] [--keep]

Exit code: 0 all run scenarios passed, 1 any failure, 2 bench could not start.
"""
from __future__ import annotations

import argparse
import concurrent.futures as cf
import datetime as dt
import hashlib
import json
import os
import re
import shlex
import subprocess
import sys
import time
import uuid
from pathlib import Path

HERE = Path(__file__).resolve().parent
ADMIN_USER, ADMIN_PASS = "bench", "bench-pass-342"
DEVICE_ID = "media-bench"
CLIENT_HDR = ('MediaBrowser Client="media-bench", Device="bench", '
              f'DeviceId="{DEVICE_ID}", Version="0.3.0"')
HW_ENCODERS = re.compile(r"\b(h264|hevc|av1)_(vaapi|qsv|nvenc|amf|videotoolbox|rkmpp|v4l2m2m)\b|\bh264_v4l2m2m\b")

# --------------------------------------------------------------------------- docker


def sh(args: list[str], *, input: bytes | None = None, check: bool = False,
       timeout: float = 600) -> subprocess.CompletedProcess:
    p = subprocess.run(args, input=input, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                       timeout=timeout)
    if check and p.returncode != 0:
        raise RuntimeError(f"{shlex.join(args)} -> {p.returncode}\n{p.stderr.decode(errors='replace')[-2000:]}")
    return p


def out(p: subprocess.CompletedProcess) -> str:
    return (p.stdout + p.stderr).decode(errors="replace")


class Bench:
    def __init__(self, a: argparse.Namespace):
        self.a = a
        self.image = a.image
        self.device = None if a.no_device else a.device
        self.run_id = uuid.uuid4().hex[:8]
        self.cname = f"media-bench-{self.run_id}"
        self.vols = {k: f"media-bench-{self.run_id}-{k}" for k in ("media", "config", "cache", "data", "kit")}
        self.outdir = Path(a.out or f"media-bench-{dt.datetime.now(dt.timezone.utc):%Y%m%dT%H%M%SZ}")
        self.outdir.mkdir(parents=True, exist_ok=True)
        self.results: list[dict] = []
        self.render_gid: str | None = None
        self.token = self.user_id = None
        self.items: dict[str, str] = {}
        self.ffmpeg = self.ffprobe = ""
        self.pci_vendor = None
        self.cmd: list[str] = []

    # ----------------------------------------------------------------- recording
    def record(self, name: str, level: str, status: str, **evidence) -> dict:
        r = {"scenario": name, "level": level, "status": status, "evidence": evidence}
        self.results.append(r)
        mark = {"pass": "PASS", "fail": "FAIL", "skip": "SKIP", "gap": "GAP "}[status]
        print(f"  {mark}  [{level:8}] {name}" + (f" — {evidence.get('summary')}" if evidence.get("summary") else ""),
              flush=True)
        with open(self.outdir / "results.jsonl", "a") as f:
            f.write(json.dumps(r) + "\n")
        return r

    # ----------------------------------------------------------------- helpers
    def dev_args(self) -> list[str]:
        if not self.device:
            return []
        return ["--device", f"{self.device}:{self.device}:rw", "--group-add", self.render_gid]

    def tool(self, entry: str, args: list[str], *, device: bool = True, user: str = "0:0",
             vols: dict[str, str] | None = None, timeout: float = 600) -> subprocess.CompletedProcess:
        v = []
        for vol, mnt in (vols or {self.vols["media"]: "/m"}).items():
            v += ["-v", f"{vol}:{mnt}"]
        return sh(["docker", "run", "--rm", "--network", "none", "--user", user, *v,
                   *(self.dev_args() if device else []), "--entrypoint", entry, self.image, *args],
                  timeout=timeout)

    def ff(self, args: list[str], **kw) -> subprocess.CompletedProcess:
        return self.tool(self.ffmpeg, ["-hide_banner", "-nostdin", *args], **kw)

    def probe_json(self, path: str, vols=None, extra: list[str] | None = None) -> dict:
        p = self.tool(self.ffprobe, ["-v", "error", "-show_streams", "-show_format", "-of", "json",
                                     *(extra or []), path], device=False, vols=vols)
        try:
            return json.loads(p.stdout or b"{}")
        except json.JSONDecodeError:
            return {"error": out(p)[-500:]}

    def yavg(self, path: str, at: float, crop: str, vols=None, ss_input: bool = True) -> float | None:
        w, h, x, y = re.match(r"(\d+)x(\d+)\+(\d+)\+(\d+)", crop).groups()
        pre = ["-ss", str(at)] if ss_input else []
        p = self.ff([*pre, "-i", path, "-frames:v", "1", "-vf",
                     f"crop={w}:{h}:{x}:{y},signalstats,metadata=print:key=lavfi.signalstats.YAVG",
                     "-f", "null", "-"], device=False, vols=vols)
        m = re.findall(r"YAVG=([\d.]+)", out(p))
        return float(m[-1]) if m else None

    # in-container HTTP (no published port; works over any DOCKER_HOST)
    def http(self, method: str, path: str, body: dict | None = None, *, save: str | None = None,
             timeout: int = 180) -> tuple[int, bytes, float]:
        hdr = CLIENT_HDR + (f', Token="{self.token}"' if self.token else "")
        cmd = ["docker", "exec", "-i", self.cname, "curl", "-sS", "-X", method, "--max-time", str(timeout),
               "-H", f"Authorization: {hdr}", "-w", "\n%{http_code} %{time_total}"]
        if body is not None:
            cmd += ["-H", "Content-Type: application/json", "--data-binary", "@-"]
        if save:
            cmd += ["-o", save]
        cmd.append(f"http://127.0.0.1:8096{path}")
        p = sh(cmd, input=json.dumps(body).encode() if body is not None else None, timeout=timeout + 30)
        raw = p.stdout
        head, _, tail = raw.rpartition(b"\n")
        try:
            code, secs = tail.decode().split()
            return int(code), head, float(secs)
        except ValueError:
            return 0, raw + p.stderr, 0.0

    def jget(self, path: str) -> dict:
        code, body, _ = self.http("GET", path)
        if code != 200:
            raise RuntimeError(f"GET {path} -> {code}: {body[:300]!r}")
        return json.loads(body)

    def logs(self, since: str | None = None) -> str:
        return out(sh(["docker", "logs", *(["--since", since] if since else []), self.cname]))

    def ffmpeg_commands(self, since: str) -> list[str]:
        cmds = []
        for line in self.logs(since).splitlines():
            if (self.ffmpeg in line or "/bench/ffmpeg" in line) and re.search(r"-(codec|c):v:0 ", line):
                try:
                    line = json.loads(line).get("message", line) if line.startswith("{") else line
                except json.JSONDecodeError:
                    pass
                cmds.append(line)
        return cmds

    def ffmpeg_procs(self) -> list[str]:
        p = sh(["docker", "exec", self.cname, "sh", "-c",
                'for d in /proc/[0-9]*; do tr "\\0" " " < $d/cmdline 2>/dev/null; echo; done'])
        return [l for l in p.stdout.decode(errors="replace").splitlines()
                if l.startswith(self.ffmpeg + " ") and " -i " in l]

    # ----------------------------------------------------------------- lifecycle
    def discover(self) -> bool:
        print("== 0. identity and hardware", flush=True)
        insp = json.loads(sh(["docker", "image", "inspect", self.image], check=True).stdout)[0]
        cmd = insp["Config"].get("Cmd") or []
        self.cmd = cmd
        self.ffmpeg = cmd[cmd.index("--ffmpeg") + 1] if "--ffmpeg" in cmd[:-1] else ""
        if not self.ffmpeg:
            self.record("identity", "env", "fail", summary="image CMD passes no --ffmpeg")
            return False
        self.ffprobe = str(Path(self.ffmpeg).with_name("ffprobe"))
        ver = out(self.tool(self.ffmpeg, ["-hide_banner", "-version"], device=False)).splitlines()
        sha = self.tool("sha256sum", [self.ffmpeg, self.ffprobe], device=False).stdout.decode().split()
        bconf = out(self.tool(self.ffmpeg, ["-hide_banner", "-buildconf"], device=False))
        archive = self.tool("cat", [str(Path(self.ffmpeg).parent.parent / "ARCHIVE.sha256")], device=False)
        uname = self.tool("uname", ["-srm"], device=False).stdout.decode().strip()
        self.record("identity", "env", "pass",
                    summary=ver[0] if ver else "?",
                    image=self.image, image_id=insp["Id"],
                    labels={k: v for k, v in (insp["Config"].get("Labels") or {}).items()
                            if "licen" in k or "revision" in k or "version" in k},
                    ffmpeg=self.ffmpeg, ffmpeg_sha256=sha[0] if sha else None,
                    ffprobe_sha256=sha[2] if len(sha) > 2 else None,
                    runtime_archive=archive.stdout.decode().strip() or None,
                    buildconf_sha256=hashlib.sha256(bconf.encode()).hexdigest(),
                    fdk=("libfdk" in bconf), kernel=uname,
                    docker_host=os.environ.get("DOCKER_HOST", "local"))
        if not self.device:
            self.record("gpu", "env", "skip", summary="--no-device: software-only run")
            return True
        node = Path(self.device).name
        p = self.tool("sh", ["-c", f"stat -c %g /hd/{node} && cat /hs/class/drm/{node}/device/vendor "
                             f"/hs/class/drm/{node}/device/device && grep DRIVER /hs/class/drm/{node}/device/uevent"],
                      device=False, vols={"/dev/dri": "/hd:ro", "/sys": "/hs:ro"})
        lines = p.stdout.decode().split()
        if p.returncode != 0 or len(lines) < 4:
            self.record("gpu", "env", "fail", summary=f"no render node {self.device} on the Docker host",
                        detail=out(p)[-400:])
            return False
        self.render_gid = lines[0]
        self.pci_vendor = lines[1]
        self.record("gpu", "env", "pass", summary=f"{lines[3]} {lines[1]}:{lines[2]} gid {self.render_gid}",
                    device=self.device, render_gid=self.render_gid, pci_vendor=lines[1],
                    pci_device=lines[2], kernel_driver=lines[3].split("=", 1)[-1])
        return True

    def make_fixtures(self) -> None:
        fx = self.a.fixture_image or self.image
        fx_ff = self.ffmpeg
        if fx != self.image:
            c = json.loads(sh(["docker", "image", "inspect", fx], check=True).stdout)[0]["Config"].get("Cmd") or []
            fx_ff = c[c.index("--ffmpeg") + 1] if "--ffmpeg" in c[:-1] else ""
            if not fx_ff:
                raise RuntimeError(f"--fixture-image {fx}: its CMD passes no --ffmpeg")
        print(f"== 1. fixtures (generated by {fx})", flush=True)
        for v in self.vols.values():
            sh(["docker", "volume", "create", v], check=True)
        m = "/m"
        steps = {
            # MPEG-2 so nothing can be direct-played or remuxed; 180 s so a seek
            # lands well past the first transcode job.
            "SDR Movie (2021)": ["-f", "lavfi", "-i", "testsrc2=duration=180:size=1280x720:rate=25",
                                 "-f", "lavfi", "-i", "sine=frequency=440:duration=180",
                                 "-c:v", "mpeg2video", "-q:v", "4", "-c:a", "mp2", "-shortest"],
            # HEVC Main10, PQ/BT.2020 with HDR10 static metadata.
            "HDR10 Movie (2021)": ["-f", "lavfi", "-i", "testsrc2=duration=30:size=1280x720:rate=25",
                                   "-f", "lavfi", "-i", "sine=frequency=330:duration=30",
                                   "-vf", "format=yuv420p10le", "-c:v", "libx265", "-preset", "ultrafast",
                                   "-x265-params", "colorprim=bt2020:transfer=smpte2084:colormatrix=bt2020nc:"
                                   "master-display=G(13250,34500)B(7500,3000)R(34000,16000)WP(15635,16450)"
                                   "L(10000000,1):max-cll=1000,400:hdr10=1",
                                   "-color_primaries", "bt2020", "-color_trc", "smpte2084",
                                   "-colorspace", "bt2020nc", "-c:a", "aac", "-shortest"],
        }
        for name, args in steps.items():
            p = sh(["docker", "run", "--rm", "--network", "none", "--user", "0:0", "-v", f"{self.vols['media']}:/m",
                    "--entrypoint", "sh", fx, "-c",
                    f'mkdir -p "{m}/{name}" && exec {fx_ff} -hide_banner -nostdin -v error -y '
                    + " ".join(shlex.quote(x) for x in args) + f' "{m}/{name}/{name}.mkv"'], timeout=900)
            if p.returncode != 0:
                raise RuntimeError(f"fixture {name}: {out(p)[-800:]}")
        # Subtitle fixtures: dark video so a burned-in white box is measurable.
        ass = ("[Script Info]\nScriptType: v4.00+\nPlayResX: 640\nPlayResY: 360\n\n[V4+ Styles]\n"
               "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, "
               "Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, "
               "Alignment, MarginL, MarginR, MarginV, Encoding\n"
               "Style: Default,DejaVu Sans,20,&H00FFFFFF,&H00FFFFFF,&H00000000,&H00000000,0,0,0,0,100,100,0,0,1,0,0,7,0,0,0,1\n\n"
               "[Events]\nFormat: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n"
               "Dialogue: 0,0:00:01.00,0:00:29.00,Default,,0,0,0,,{\\pos(160,260)\\p1}m 0 0 l 320 0 320 60 0 60{\\p0}\n")
        pgs = sh([sys.executable, "-I", str(HERE / "gen-pgs.py"), "/dev/stdout", "--box", "320x60+160+260"],
                 check=True).stdout
        sup, geom = pgs[:-len(b"320x60+160+260\n")], "320x60+160+260"
        self.sub_box = geom
        for kind, payload, codec in (("ASS", ass.encode(), "ass"), ("PGS", sup, "copy")):
            name = f"{kind} Movie (2021)"
            ext = "ass" if kind == "ASS" else "sup"
            script = (f'mkdir -p "{m}/{name}" && cat > /tmp/s.{ext} && exec {fx_ff} -hide_banner -nostdin '
                      f'-v error -y -f lavfi -i color=c=0x202020:s=640x360:d=30:r=25 '
                      f'-f lavfi -i sine=frequency=550:duration=30 -i /tmp/s.{ext} -map 0:v -map 1:a -map 2:s '
                      f'-c:v mpeg2video -q:v 4 -c:a mp2 -c:s {codec} -metadata:s:s:0 language=eng -shortest '
                      f'"{m}/{name}/{name}.mkv"')
            p = sh(["docker", "run", "--rm", "-i", "--network", "none", "--user", "0:0",
                    "-v", f"{self.vols['media']}:/m", "--entrypoint", "sh", fx, "-c", script],
                   input=payload, timeout=300)
            if p.returncode != 0:
                raise RuntimeError(f"fixture {name}: {out(p)[-800:]}")
        self.tool("chmod", ["-R", "a+rX", m], device=False)
        self.tool("chown", ["-R", "10000:10000", "/c", "/k", "/d"], device=False,
                  vols={self.vols["config"]: "/c", self.vols["cache"]: "/k", self.vols["data"]: "/d"})
        ls = self.tool("sh", ["-c", f"cd {m} && find . -name '*.mkv' -exec sha256sum {{}} +"], device=False)
        # A fixture is only evidence if it is what it claims to be. The HDR10 one
        # must really be 10-bit PQ/BT.2020: an encoder that silently drops to 8 bits
        # (a single-depth libx265) produces a file the server rightly calls SDR.
        hv = next((x for x in self.probe_json(f"{m}/HDR10 Movie (2021)/HDR10 Movie (2021).mkv").get("streams", [])
                   if x.get("codec_type") == "video"), {})
        hdr_ok = (hv.get("pix_fmt") == "yuv420p10le" and hv.get("color_transfer") == "smpte2084"
                  and hv.get("color_primaries") == "bt2020")
        self.record("fixtures", "env", "pass" if hdr_ok else "fail",
                    summary=f"4 fixtures by {fx}; HDR10 = {hv.get('pix_fmt')} {hv.get('color_transfer')} "
                            f"{hv.get('color_primaries')}" + ("" if hdr_ok else
                            " — NOT 10-bit PQ: pass --fixture-image with a Main10-capable libx265"),
                    fixture_image=fx, sha256=ls.stdout.decode().strip().splitlines())
        if not hdr_ok:
            raise RuntimeError("HDR10 fixture is not 10-bit PQ/BT.2020")

    def start_server(self, with_device: bool, ffmpeg: str | None = None) -> float:
        sh(["docker", "rm", "-f", self.cname])
        cmd = []
        if ffmpeg:
            cmd = list(self.cmd)
            cmd[cmd.index("--ffmpeg") + 1] = ffmpeg
        t0 = time.monotonic()
        sh(["docker", "run", "-d", "--name", self.cname, "--security-opt", "no-new-privileges:true",
            *(self.dev_args() if with_device else []),
            "-v", f"{self.vols['config']}:/config", "-v", f"{self.vols['cache']}:/cache",
            "-v", f"{self.vols['data']}:/data", "-v", f"{self.vols['media']}:/media:ro",
            "-v", f"{self.vols['kit']}:/bench:ro", self.image, *cmd],
           check=True)
        streak = 0
        while time.monotonic() - t0 < 300:
            code, _, _ = self.http("GET", "/health", timeout=5)
            streak = streak + 1 if code == 200 else 0
            if streak >= 3:
                return time.monotonic() - t0
            time.sleep(1)
        raise RuntimeError("server never answered /health 200\n" + self.logs()[-3000:])

    def onboard(self) -> None:
        self.http("GET", "/Startup/User")
        self.http("POST", "/Startup/User", {"Name": ADMIN_USER, "Password": ADMIN_PASS})
        self.http("POST", "/Startup/Complete")
        code, body, _ = self.http("POST", "/Users/AuthenticateByName", {"Username": ADMIN_USER, "Pw": ADMIN_PASS})
        d = json.loads(body)
        self.token, self.user_id = d["AccessToken"], d["User"]["Id"]
        enc = self.jget("/System/Configuration/encoding")
        # Tone-mapping on, HEVC 10-bit hardware decode allowed. The hardware TYPE is
        # left to the server's own startup decision — that decision is under test.
        enc.update({"EnableTonemapping": True, "EnableDecodingColorDepth10Hevc": True,
                    "HardwareDecodingCodecs": ["h264", "hevc", "mpeg2video", "vc1", "vp9", "av1"]})
        code, body, _ = self.http("POST", "/System/Configuration/encoding", enc)
        if code not in (200, 204):
            raise RuntimeError(f"encoding config -> {code} {body[:200]!r}")
        self.http("POST", "/Library/VirtualFolders?name=Movies&collectionType=movies&paths=%2Fmedia&refreshLibrary=true",
                  {"LibraryOptions": {"PathInfos": [{"Path": "/media"}]}})
        deadline = time.monotonic() + 180
        while time.monotonic() < deadline:
            d = self.jget(f"/Items?userId={self.user_id}&recursive=true&includeItemTypes=Movie&fields=Path,MediaStreams")
            self.items = {i["Name"].split(" Movie")[0]: i["Id"] for i in d.get("Items", [])}
            if len(self.items) >= 4:
                return
            time.sleep(2)
        raise RuntimeError(f"library scan found only {sorted(self.items)}")

    def decision(self) -> str:
        lines = [l for l in self.logs().splitlines() if "Hardware acceleration decision:" in l]
        return lines[-1].split("Hardware acceleration decision:", 1)[1].strip().strip('"}') if lines else ""

    # ----------------------------------------------------------------- HLS client
    def hls(self, key: str, tag: str, *, segments: int = 3, first: int = 0, container: str = "ts",
            extra: str = "") -> dict:
        """Plays an item the way a client does: master -> main -> segments. Returns evidence."""
        item = self.items[key]
        ps = uuid.uuid4().hex
        q = (f"MediaSourceId={item}&VideoCodec=h264&AudioCodec=aac&SegmentContainer={container}"
             f"&PlaySessionId={ps}&DeviceId={DEVICE_ID}&MaxWidth=1280&VideoBitrate=4000000"
             f"&AudioBitrate=128000&TranscodingMaxAudioChannels=2&BreakOnNonKeyFrames=false{extra}")
        since = dt.datetime.now(dt.timezone.utc).isoformat()
        t0 = time.monotonic()
        code, master, _ = self.http("GET", f"/Videos/{item}/master.m3u8?{q}")
        ev = {"play_session": ps, "master_http": code}
        if code != 200:
            ev["error"] = master[:300].decode(errors="replace")
            return ev
        main_rel = next(l for l in master.decode().splitlines() if l and not l.startswith("#"))
        code, main, _ = self.http("GET", f"/Videos/{item}/{main_rel}")
        ev["main_http"] = code
        segs = [l for l in main.decode().splitlines() if l and not l.startswith("#")]
        durs = [float(x) for x in re.findall(r"#EXTINF:([\d.]+)", main.decode())]
        ev["segment_offset_seconds"] = round(sum(durs[:first]), 3)
        ev["playlist_segments"] = len(segs)
        ev["segment_urls"] = [f"/Videos/{item}/hls1/main/{rel.split('/')[-1]}" for rel in segs]
        init = re.search(r'#EXT-X-MAP:URI="([^"]+)"', main.decode())
        wdir = f"/cache/bench/{tag}"
        sh(["docker", "exec", self.cname, "mkdir", "-p", wdir])
        files, ok = [], True
        if init:
            c, _, _ = self.http("GET", f"/Videos/{item}/hls1/main/{init.group(1).split('/')[-1]}", save=f"{wdir}/init.mp4")
            ev["init_http"] = c
            ok &= c == 200
        for n, rel in enumerate(segs[first:first + segments], start=first):
            c, _, secs = self.http("GET", f"/Videos/{item}/hls1/main/{rel.split('/')[-1]}", save=f"{wdir}/{n}.seg")
            if n == first:
                ev["first_segment_seconds"] = round(time.monotonic() - t0, 2)
            files.append({"n": n, "http": c})
            ok &= c == 200
        ev["segments"] = files
        # A playable stream for probing: init + segments concatenated.
        cat = " ".join(([f"{wdir}/init.mp4"] if init else []) + [f"{wdir}/{f['n']}.seg" for f in files])
        sh(["docker", "exec", self.cname, "sh", "-c", f"cat {cat} > {wdir}/stream.{'mp4' if init else 'ts'}"])
        ev["stream"] = f"{wdir}/stream.{'mp4' if init else 'ts'}"
        ev["bytes"] = int(sh(["docker", "exec", self.cname, "stat", "-c", "%s", ev["stream"]]).stdout or 0)
        cmds = self.ffmpeg_commands(since)
        ev["ffmpeg_command"] = cmds[-1] if cmds else None
        m = re.search(r"-(?:codec|c):v:0 (\S+)", ev["ffmpeg_command"] or "")
        ev["video_encoder"] = m.group(1) if m else None
        m = re.search(r"-(?:codec|c):a:0 (\S+)", ev["ffmpeg_command"] or "")
        ev["audio_encoder"] = m.group(1) if m else None
        ev["all_ok"] = ok and ev["bytes"] > 20000
        return ev

    def probe_stream(self, ev: dict) -> dict:
        return self.probe_json(ev["stream"], vols={self.vols["cache"]: "/cache"})

    def stop_session(self, ps: str) -> int:
        code, _, _ = self.http("DELETE", f"/Videos/ActiveEncodings?deviceId={DEVICE_ID}&playSessionId={ps}")
        return code

